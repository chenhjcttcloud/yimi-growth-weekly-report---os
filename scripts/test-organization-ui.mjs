import {chromium} from 'playwright';
import {spawn} from 'node:child_process';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';

const dir=await mkdtemp(path.join(tmpdir(),'organization-ui-'));
const port=7500+Math.floor(Math.random()*300),base=`http://127.0.0.1:${port}`;
const server=spawn(process.execPath,['server/index.mjs'],{env:{...process.env,AUTH_MODE:'mock',DEV_VIEW_SWITCH_ENABLED:'true',SERVER_PORT:String(port),APP_DATA_DIR:'src/data',WEEKLY_REPORT_DB_PATH:path.join(dir,'test.sqlite'),LARK_REPORT_AUTO_SYNC_ENABLED:'false',LARK_AUTH_MONITOR_ENABLED:'false',SCORING360_REMINDER_ENABLED:'false',WEEKLY_REMINDER_ENABLED:'false'},stdio:'ignore'});
let browser;
try{
 for(let i=0;i<100;i++){try{if((await fetch(base+'/health')).ok)break;}catch{}await new Promise(r=>setTimeout(r,50));}
 browser=await chromium.launch({channel:'chrome',headless:true});
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 await context.request.post(base+'/api/dev/views',{data:{id:'hr'}});
 const page=await context.newPage(),consoleErrors=[];
 page.on('pageerror',e=>consoleErrors.push(e.message));
 page.on('response',async r=>{if(r.url().endsWith('/api/departments/layout')&&!r.ok())console.error('Layout save failed:',await r.text());});
 await page.goto(base);
 await page.getByRole('button',{name:'部门管理',exact:true}).click();
 await page.getByRole('button',{name:'组织与负责人',exact:true}).click();
 await page.getByRole('navigation',{name:'组织部门树'}).waitFor();
 const before=await (await context.request.get(base+'/api/departments')).json();
 assert(before.employees.length>0);
 await page.getByRole('button',{name:'新增一级部门',exact:true}).click();
 await page.getByRole('textbox',{name:'部门名称',exact:true}).fill('国内事业部');
 await page.getByRole('button',{name:'新增子部门',exact:true}).click();
 await page.getByRole('textbox',{name:'部门名称',exact:true}).fill('产品推广');
 await page.getByRole('combobox',{name:'部门负责人',exact:true}).click();
 await page.getByRole('listbox',{name:'部门负责人',exact:true}).getByRole('option').filter({hasText:before.employees[0].name}).first().click();
 assert(await page.getByRole('checkbox',{name:'兼任负责人',exact:true}).isChecked());
 const unsaved=await (await context.request.get(base+'/api/departments')).json();
 assert(!unsaved.departments.some(d=>d.name==='产品推广'),'drafts must not persist before confirmation');
 await page.getByRole('button',{name:'预览并保存',exact:true}).click();
 await page.getByRole('dialog',{name:'确认组织架构调整'}).waitFor();
 await page.getByRole('dialog').evaluate(el=>Promise.all(el.getAnimations().map(a=>a.finished)));
 const overlay=await page.locator('.org-modal-backdrop').boundingBox();
 assert.equal(overlay.x,0);assert.equal(overlay.y,0);assert.equal(overlay.width,1440,'preview must cover the entire viewport, not be clipped by the page');
 await page.screenshot({path:'outputs/organization-preview.png',fullPage:false});
 await page.getByRole('button',{name:'返回编辑',exact:true}).click();
 await page.getByRole('button',{name:'预览并保存',exact:true}).click();
 await page.getByRole('button',{name:'确认保存组织架构',exact:true}).click();
 await page.getByRole('status').filter({hasText:'组织架构已保存'}).waitFor();
 const saved=await (await context.request.get(base+'/api/departments')).json(),child=saved.departments.find(d=>d.name==='产品推广'),parent=saved.departments.find(d=>d.name==='国内事业部');
 assert.equal(child.parent_id,parent.id);assert.equal(child.leader_mode,'concurrent');
 assert.equal(saved.employees[0].department,before.employees[0].department);
 await page.getByRole('status').filter({hasText:'组织架构已保存'}).waitFor({state:'visible'});
 await page.locator('.content-shell').evaluate(el=>el.scrollTo({top:0}));
 await page.screenshot({path:'outputs/organization-editor.png',fullPage:false});
 const style=await page.locator('.org-editor').evaluate(el=>({radius:getComputedStyle(el).borderRadius,columns:getComputedStyle(el.querySelector('.org-workspace')).gridTemplateColumns}));
 assert.equal(style.radius,'18px');assert(style.columns.split(' ').length===2,'desktop has a two-column organization workspace');
 // Hover controls remain keyboard-accessible and search preserves parent context.
 await page.getByRole('searchbox',{name:'搜索组织部门'}).fill('产品推广');
 await page.getByRole('navigation',{name:'组织部门树'}).getByRole('button',{name:/国内事业部/}).first().waitFor();
 await page.getByRole('searchbox',{name:'搜索组织部门'}).fill('');
 // Reorder through drag-and-drop, then cancel an attempted navigation with dirty data.
 const tree=page.getByRole('navigation',{name:'组织部门树'}),row=tree.locator('.org-tree-row').filter({hasText:'产品推广'});
 await page.locator('.org-root-drop').scrollIntoViewIfNeeded();
 const source=await row.boundingBox(),target=await page.locator('.org-root-drop').boundingBox();
 assert(source&&target);
 await page.mouse.move(source.x+8,source.y+30);await page.mouse.down();
 await page.mouse.move(source.x+20,source.y+35,{steps:5});
 await page.mouse.move(target.x+40,target.y+15,{steps:15});
 await page.mouse.move(target.x+45,target.y+20,{steps:3});await page.mouse.up();
 await page.getByRole('button',{name:'预览并保存',exact:true}).click();
 await page.getByRole('button',{name:'确认保存组织架构',exact:true}).click();
 await page.getByRole('status').filter({hasText:'组织架构已保存'}).waitFor();
 assert.equal((await (await context.request.get(base+'/api/departments')).json()).departments.find(d=>d.id===child.id).parent_id,'');
 await page.getByRole('textbox',{name:'部门名称',exact:true}).fill('尚未保存的名称');
 page.once('dialog',d=>d.dismiss());
 await page.getByRole('button',{name:'部门概览',exact:true}).click();
 assert.equal(await page.getByRole('textbox',{name:'部门名称',exact:true}).inputValue(),'尚未保存的名称');
 page.once('dialog',d=>d.accept());await page.getByRole('button',{name:'撤销修改',exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'mobile page must not overflow');
 assert.equal(await page.locator('.org-workspace').evaluate(el=>getComputedStyle(el).gridTemplateColumns.split(' ').length),1,'mobile stacks the workspace');
 await page.locator('.content-shell').evaluate(el=>el.scrollTo({top:0}));
 await page.screenshot({path:'outputs/organization-mobile.png',fullPage:false});
 await page.locator('.org-detail').scrollIntoViewIfNeeded();
 await page.screenshot({path:'outputs/organization-mobile-detail.png',fullPage:false});
 await page.setViewportSize({width:1440,height:1000});
 // Other system entries use the same component, including the former native datalist.
 await page.getByRole('button',{name:'评分工作台',exact:true}).click();
 await page.getByRole('combobox',{name:'选择绩效月份',exact:true}).click();
 await page.getByRole('listbox',{name:'选择绩效月份',exact:true}).getByRole('option').first().click();
 await page.getByRole('button',{name:'系统设置',exact:true}).click();
 await page.getByRole('navigation',{name:'设置分类'}).getByRole('button',{name:/协作评分关系/}).click();
 await page.getByRole('combobox',{name:'被评分人',exact:true}).click();
 await page.getByRole('searchbox',{name:'搜索被评分人',exact:true}).fill('未保存的测试成员');
 await page.getByRole('option',{name:'使用“未保存的测试成员”',exact:true}).click();
 assert((await page.getByRole('combobox',{name:'被评分人',exact:true}).textContent()).includes('未保存的测试成员'));
 assert.equal(await page.locator('select:visible, datalist:visible').count(),0,'system entries must not expose native dropdowns');
 // Server-side authorization applies to the new write endpoint as well.
 const views=await (await context.request.get(base+'/api/dev/views')).json();
 const employee=views.views.find(v=>v.role==='employee');
 await context.request.post(base+'/api/dev/views',{data:{id:employee.id}});
 assert.equal((await context.request.post(base+'/api/departments/layout',{data:{}})).status(),403);
 assert.deepEqual(consoleErrors,[]);
 console.log('Organization UI tests passed: two-level setup, concurrent leader, preview, save, drag, discard protection, mobile layout, write permissions. Screenshot: outputs/organization-editor.png');
}finally{if(browser)await browser.close();server.kill();await rm(dir,{recursive:true,force:true});}
